# Shared helpers for the trainer scripts. Source it; don't run it.

# Rewrites flux/syncroot/base/kustomization.yaml so its resources list exactly
# matches the participant files in flux/syncroot/base/ (sorted).
sync_syncroot_resources() {
  local base="$1/flux/syncroot/base" f
  {
    echo "# Training syncroot: one OCIRepository + Flux Kustomization per participant."
    echo "# Generated by scripts/add-participant.sh and scripts/cleanup.sh; don't edit by hand."
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    if ls "$base"/*.yaml 2>/dev/null | grep -qv '/kustomization.yaml$'; then
      echo "resources:"
      for f in $(ls "$base"/*.yaml | sort); do
        [[ "$(basename "$f")" == kustomization.yaml ]] && continue
        echo "  - $(basename "$f")"
      done
    else
      echo "resources: []"
    fi
  } >"$base/kustomization.yaml.tmp"
  mv "$base/kustomization.yaml.tmp" "$base/kustomization.yaml"
}
